// Detecta o idioma do navegador (usado quando não há preferência salva,
// ex.: primeiro acesso / logo após criar a conta).
export function detectLang() {
  const n = ((typeof navigator !== 'undefined' && (navigator.language || navigator.languages?.[0])) || 'pt').toLowerCase()
  return n.startsWith('pt') ? 'pt' : 'en'
}

